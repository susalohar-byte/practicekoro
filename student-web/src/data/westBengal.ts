/** StudentProfileModel.normalizeCategoryCode */
export function normalizeCategoryCode(raw: string | null | undefined): string {
  if (!raw || !raw.trim()) return 'NOT_SPECIFIED';
  const u = raw.trim().toUpperCase();
  if (u in CATEGORIES) return u;
  if (u.includes('OBC_A') || u.includes('OBC-A') || u.includes('OBC A')) return 'OBC_A';
  if (u.includes('OBC_B') || u.includes('OBC-B') || u.includes('OBC B')) return 'OBC_B';
  if (u.includes('SC') || u.includes('SCHEDULED CASTE')) return 'SC';
  if (u.includes('ST') || u.includes('SCHEDULED TRIBE')) return 'ST';
  if (u.includes('EWS')) return 'EWS';
  if (u.includes('PWD')) return 'PWD';
  if (u.includes('GEN') || u.includes('UR') || u.includes('UNRESERVED')) return 'GEN';
  return 'NOT_SPECIFIED';
}

