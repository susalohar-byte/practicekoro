export const isValidDistrict = (district: string): district is WestBengalDistrict => {
  return WEST_BENGAL_DISTRICTS.includes(district as WestBengalDistrict);
};

export function getBlocksForDistrict(district?: string | null): readonly string[] {
  if (!district) return [];
  const clean = district.trim().toLowerCase();
  const found = (Object.keys(WEST_BENGAL_BLOCKS) as WestBengalDistrict[]).find(
    (d) => d.toLowerCase() === clean
  );
  return found ? WEST_BENGAL_BLOCKS[found] : [];
}
